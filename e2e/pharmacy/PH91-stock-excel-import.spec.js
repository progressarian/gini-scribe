import { test, expect } from "@playwright/test";
import ExcelJS from "exceljs";
import { apiAs, loginAs } from "../helpers/auth.mjs";
import { one, query } from "../helpers/db.mjs";
import { gotoReady } from "../helpers/browser.mjs";
import { pickDate, pickOption } from "../helpers/pickers.mjs";
import { assertTestDatabase } from "../setup/guard.mjs";

if (process.env.DATABASE_URL) assertTestDatabase(process.env.DATABASE_URL);

const TAG = `PH91${Date.now().toString(36).toUpperCase()}`;
const YEAR = new Date().getFullYear() + 2;
const XLSX = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
const BASE = "/api/pharmacy/purchases/stock-import";

const HEADERS = [
  "Item name",
  "HSN Code",
  "Location",
  "Unit",
  "Batch No",
  "Pack Size",
  "MRP",
  "PTR",
  "Total Stock",
  "Source",
  "Supplier Name",
  "S.Rate",
  "S.RateTot",
  "P.Rate",
  "P.RateTot",
  "LP.Rate",
  "LP.RateTot",
  "Expiry Date",
  "GST",
  "Company Name",
  "Generic Name",
  "Item Category",
  "Item Type",
];

const row = (r) => [
  r.name,
  r.hsn ?? "30049099",
  "",
  "1",
  r.batch,
  r.pack ?? "0",
  r.mrp,
  "",
  r.qty,
  "Purchase",
  r.vendor,
  r.sale ?? r.mrp,
  "",
  r.purchase,
  "",
  r.lp ?? Math.round(r.purchase * 105) / 100,
  "",
  r.expiry ?? `Dec-${YEAR}`,
  r.gst ?? 5,
  r.company ?? "",
  r.generic ?? "",
  r.category ?? "",
  "",
];

async function darpanFile(tag) {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet("Stock report");
  sheet.addRow(["BATCH WISE STOCK REPORT"]);
  sheet.addRow(["GENERATED BY: DARPAN [23/11/2026 01:18:49 PM]"]);
  sheet.addRow(["STORE NAME: TEST STORE"]);
  sheet.addRow([]);
  sheet.addRow(HEADERS);
  [
    {
      name: `${tag} METFORMIN 500 TAB`,
      batch: "MF01",
      pack: "1*10",
      mrp: 100,
      qty: 5,
      purchase: 60,
      vendor: `${tag} STAR PHARMA`,
      category: "TAB",
      company: "USV",
    },
    {
      name: `${tag} METFORMIN 500 TAB`,
      batch: "MF01",
      pack: "1*10",
      mrp: 120,
      qty: 3,
      purchase: 70,
      vendor: `${tag} GUPTA AGENCIES`,
      category: "TAB",
    },
    {
      name: `${tag} CREPE BANDAGE`,
      batch: "CB 22",
      mrp: 250,
      qty: 4,
      purchase: 100,
      vendor: "Opening Stock",
      category: "SURGICAL",
    },
    {
      name: `${tag} OLD SYRUP`,
      batch: "OS1",
      mrp: 90,
      qty: 2,
      purchase: 50,
      vendor: `${tag} STAR PHARMA`,
      expiry: "Jan-2020",
    },
  ].forEach((r) => sheet.addRow(row(r)));
  sheet.addRow([]);
  sheet.addRow(["TOTAL"]);
  return Buffer.from(await workbook.xlsx.writeBuffer());
}

test.describe.configure({ mode: "serial" });

test.describe("PH91 stock import from the old system's Excel", () => {
  let admin;
  let file;

  test.beforeAll(async () => {
    admin = await apiAs("pharmacy_admin");
    file = await darpanFile(TAG);
  });

  test.afterAll(async () => {
    await admin?.dispose();
  });

  test("preview merges duplicate batches, leaves out expired rows and writes nothing", async () => {
    const response = await admin.post(`${BASE}/preview`, {
      data: file,
      headers: { "Content-Type": XLSX },
    });
    expect(response.status()).toBe(200);
    const preview = await response.json();
    expect(preview.counts).toMatchObject({
      rows: 4,
      batches: 2,
      medicines: 2,
      vendors: 1,
      merged: 1,
      leftOut: 1,
    });
    expect(preview.leftOut[0].reason).toContain("Expired");
    expect(preview.merged[0]).toMatchObject({ qty_packs: 8, mrp: 120, sale_rate: 120 });
    expect(preview.newVendors).toEqual([`${TAG} GUPTA AGENCIES`]);
    const created = await one(
      `SELECT count(*)::int AS n FROM pharmacy_medicines WHERE name LIKE $1`,
      [`${TAG}%`],
    );
    expect(created.n).toBe(0);
  });

  test("import creates vendors, medicines and posted opening stock that matches the sheet", async () => {
    const preview = await (
      await admin.post(`${BASE}/preview`, { data: file, headers: { "Content-Type": XLSX } })
    ).json();
    const stale = await admin.post(`${BASE}?hash=${"0".repeat(64)}`, {
      data: file,
      headers: { "Content-Type": XLSX },
    });
    expect(stale.status()).toBe(409);

    const response = await admin.post(`${BASE}?hash=${preview.hash}&name=report.xlsx`, {
      data: file,
      headers: { "Content-Type": XLSX },
    });
    expect(response.status()).toBe(200);
    const result = await response.json();
    expect(result.created).toEqual({ vendors: 1, medicines: 2, batches: 2 });
    expect(result.match).toMatchObject({ checked: 2, matched: 2, mismatches: [] });
    expect(result.receipts).toHaveLength(1);

    const receipt = await one(
      `SELECT kind, status, vendor_id, invoice_no FROM pharmacy_purchases WHERE id = $1`,
      [result.receipts[0].id],
    );
    expect(receipt).toEqual({
      kind: "opening",
      status: "posted",
      vendor_id: null,
      invoice_no: null,
    });

    const tablet = await one(
      `SELECT m.form, m.pack_size, m.pack_label, m.needs_review, m.allow_loose_sale, b.batch_no, b.mrp, b.sale_rate,
              b.purchase_rate, v.name AS vendor, v.phone, s.qty_units
         FROM pharmacy_batches b
         JOIN pharmacy_medicines m ON m.id = b.medicine_id
         LEFT JOIN pharmacy_vendors v ON v.id = b.vendor_id
         JOIN pharmacy_stock s ON s.batch_id = b.id
        WHERE m.name = $1`,
      [`${TAG} METFORMIN 500 TAB`],
    );
    expect(tablet).toMatchObject({
      form: "TAB",
      pack_size: 10,
      pack_label: "strip",
      needs_review: true,
      allow_loose_sale: false,
      batch_no: "MF01",
      mrp: "120.00",
      sale_rate: "120.00",
      purchase_rate: "70.00",
      vendor: `${TAG} GUPTA AGENCIES`,
      phone: null,
      qty_units: 80,
    });

    const bandage = await one(
      `SELECT m.form, b.batch_no, b.vendor_id, s.qty_units
         FROM pharmacy_batches b
         JOIN pharmacy_medicines m ON m.id = b.medicine_id
         JOIN pharmacy_stock s ON s.batch_id = b.id
        WHERE m.name = $1`,
      [`${TAG} CREPE BANDAGE`],
    );
    expect(bandage).toEqual({
      form: "SURG. ITEM",
      batch_no: "CB22",
      vendor_id: null,
      qty_units: 4,
    });

    const old = await query(`SELECT 1 FROM pharmacy_medicines WHERE name = $1`, [
      `${TAG} OLD SYRUP`,
    ]);
    expect(old.rows ?? old).toHaveLength(0);
  });

  test("importing the same sheet again adds nothing", async () => {
    const preview = await (
      await admin.post(`${BASE}/preview`, { data: file, headers: { "Content-Type": XLSX } })
    ).json();
    expect(preview.counts).toMatchObject({ batches: 0, medicines: 0, vendors: 0, leftOut: 4 });
    expect(preview.leftOut.filter((r) => r.reason.includes("already in stock"))).toHaveLength(3);
  });

  test("the pharmacist cannot import stock", async () => {
    const pharmacist = await apiAs("pharmacy");
    const response = await pharmacist.post(`${BASE}/preview`, {
      data: file,
      headers: { "Content-Type": XLSX },
    });
    expect(response.status()).toBe(403);
    await pharmacist.dispose();
  });

  test("pharmacy admin imports the sheet from the stock page", async ({ page }) => {
    const tag = `${TAG}UI`;
    await loginAs(page, "pharmacy_admin");
    await gotoReady(
      page,
      "/pharmacy/stock",
      () => page.getByRole("button", { name: "Import stock (Excel)" }),
      { timeout: 30000 },
    );
    await page.getByRole("button", { name: "Import stock (Excel)" }).click();
    const dialog = page.getByRole("dialog", { name: "Import stock from Excel" });
    await dialog.getByLabel("Stock sheet file").setInputFiles({
      name: "batch_wise_stock_report.xlsx",
      mimeType: XLSX,
      buffer: await darpanFile(tag),
    });
    await expect(dialog.getByText("Expired on 2020-01-31")).toBeVisible();
    const importButton = dialog.getByRole("button", { name: "Import 2 batches" });
    await expect(importButton).toBeDisabled();
    await dialog.getByLabel(/I have checked the summary/).check();
    await importButton.click();
    await expect(dialog.getByText("Stock imported")).toBeVisible({ timeout: 30000 });
    await expect(dialog.getByText(/2 of 2 batches match the sheet/)).toBeVisible();
    await dialog.getByRole("button", { name: "Close" }).click();
    await expect(dialog).toBeHidden();
  });

  test("pharmacy admin adds a batch with the Add stock form", async ({ page }) => {
    await loginAs(page, "pharmacy_admin");
    await gotoReady(
      page,
      "/pharmacy/stock",
      () => page.getByRole("button", { name: "Add stock" }),
      {
        timeout: 30000,
      },
    );
    await page.getByRole("button", { name: "Add stock" }).click();
    const dialog = page.getByRole("dialog", { name: "Add stock" });
    await dialog.getByRole("button", { name: "Add stock" }).click();
    await expect(dialog.getByText("Choose the medicine.")).toBeVisible();

    await dialog.getByRole("combobox", { name: "Medicine" }).fill(`${TAG} METFORMIN`);
    await page.getByRole("option", { name: new RegExp(`${TAG} METFORMIN 500 TAB`) }).click();
    await pickOption(dialog, "Vendor", `${TAG} GUPTA AGENCIES`);
    await dialog.getByLabel("Batch").fill("mf 02");
    await pickDate(dialog, "Expiry", `${YEAR}-06-15`);
    await dialog.getByLabel("Qty (packs)").fill("6");
    await dialog.getByLabel("Purchase rate per pack").fill("65");
    await expect(dialog.getByLabel("MRP per pack")).toHaveValue("120");
    await dialog.getByRole("button", { name: "Add stock" }).click();
    await expect(dialog).toBeHidden({ timeout: 15000 });

    const added = await one(
      `SELECT b.batch_no, b.mrp, v.name AS vendor, s.qty_units, p.kind, p.status
         FROM pharmacy_batches b
         JOIN pharmacy_medicines m ON m.id = b.medicine_id
         JOIN pharmacy_vendors v ON v.id = b.vendor_id
         JOIN pharmacy_stock s ON s.batch_id = b.id
         JOIN pharmacy_purchase_lines pl ON pl.batch_id = b.id
         JOIN pharmacy_purchases p ON p.id = pl.purchase_id
        WHERE m.name = $1 AND b.batch_no = 'MF02'`,
      [`${TAG} METFORMIN 500 TAB`],
    );
    expect(added).toEqual({
      batch_no: "MF02",
      mrp: "120.00",
      vendor: `${TAG} GUPTA AGENCIES`,
      qty_units: 60,
      kind: "opening",
      status: "posted",
    });
  });

  test("the pharmacist does not see the stock loading buttons", async ({ page }) => {
    await loginAs(page, "pharmacy");
    await gotoReady(page, "/pharmacy/stock", () =>
      page.getByRole("heading", { name: "Pharmacy stock" }),
    );
    await expect(page.getByRole("button", { name: "Add stock" })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Import stock (Excel)" })).toHaveCount(0);
  });
});
